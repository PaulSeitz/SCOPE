"""Compact main-text transfer tables, built from the CSVs that generate.py writes.

Run after generate.py: python figures/evaluation/compact_transfer_tables.py
The full tables (with SDs and random actions) stay in the appendix.
"""
import csv
import sys
from pathlib import Path

TABLES = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent / 'tables'
NAMES = {'namethisgame': 'Name This Game', 'seaquest': 'Seaquest', 'spaceinvaders': 'Space Invaders',
         'beamrider': 'Beam Rider', 'asteroids': 'Asteroids', 'pong': 'Pong', 'breakout': 'Breakout',
         'freeway': 'Freeway', 'phoenix': 'Phoenix'}
SOURCES = ['seaquest', 'namethisgame']
ARMS = ['skills_ego', 'tandem_ocnative_skills', 'tandem_pixel_slots_skills']
HEADER = '% Generated by figures/evaluation/compact_transfer_tables.py from the generate.py CSVs; edit the script, not this file.\n'


def fmt(value, bold=False):
    if value is None:
        return r'\textemdash'
    text = f'{value:,.0f}' if abs(value) >= 100 else f'{value:.1f}'
    text = text.replace(',', '{,}')
    return f'$\\mathbf{{{text}}}$' if bold else f'${text}$'


def num(text):
    return float(text) if text not in ('', None) else None


def read(name):
    with open(TABLES / name, newline='') as handle:
        return list(csv.DictReader(handle))


def write_table(path, caption_short, caption, label, colspec, head, rows):
    lines = [HEADER, r'\begin{table}[!htbp]', r'  \centering', r'  \footnotesize', r'  \setlength{\tabcolsep}{4pt}',
             f'  \\caption[{caption_short}]{{{caption}}}', f'  \\label{{{label}}}',
             f'  \\begin{{tabular*}}{{\\linewidth}}{{@{{\\extracolsep{{\\fill}}}}{colspec}@{{}}}}', r'    \toprule']
    lines += ['    ' + line for line in head]
    lines.append(r'    \midrule')
    lines += ['    ' + ' & '.join(row) + r' \\' for row in rows]
    lines += [r'    \bottomrule', r'  \end{tabular*}', r'\end{table}', '']
    path.write_text('\n'.join(lines))


reference = read('reference_transfer.csv')
native = {row['target']: num(row['native_mean']) for row in reference}

rows = []
for row in reference:
    values = [num(row['heuristic_random'])] + [num(row[source + '_mean']) for source in SOURCES]
    best = max(v for v in values if v is not None)
    rows.append([NAMES[row['target']]] + [fmt(v, v == best) for v in values] + [fmt(native[row['target']])])
write_table(TABLES / 'reference_transfer_compact.tex', 'Transfer of SCOPE skills',
            r'\textbf{Transferred skills stay far below native training in every target except Freeway.} '
            r'Mean episodic return over five checkpoints for the skills of SCOPE, transferred zero-shot under the target heuristic, '
            r'against the untrained-skill control and native training of SCOPE. Bold marks the highest value per row, excluding native training. '
            r'Appendix~\ref{sec:appendix-transfer-complete} adds random actions and standard deviations.',
            'tab:eval-transfer', 'lrrr|r',
            [r'& \multicolumn{1}{c}{Untrained} & \multicolumn{2}{c|}{SCOPE skills from} & Native \\ \cmidrule(lr){3-4}',
             r'Target & skills & Seaquest & Name This Game & training \\'],
            rows)

tandem = {(row['source'], row['target'], row['arm']): num(row['mean']) for row in read('tandem_transfer.csv')}
rows = []
for row in reference:
    target = row['target']
    cells = [NAMES[target]]
    for source in SOURCES:
        values = [tandem.get((source, target, arm)) if source != target else None for arm in ARMS]
        present = [v for v in values if v is not None]
        best = max(present) if present else None
        cells += [fmt(v, v is not None and v == best) for v in values]
    cells.append(fmt(native[target]))
    rows.append(cells)
write_table(TABLES / 'tandem_transfer_compact.tex', 'Transfer of tandem-trained skills',
            r'\textbf{Pixel tandem skills exceed the skills of SCOPE in most pairs but remain far below native training.} '
            r'Mean episodic return over five checkpoints for skills transferred zero-shot under the target heuristic. '
            r'Bold marks the highest of the three skill sets per source. '
            r'Appendix~\ref{sec:appendix-transfer-complete} adds standard deviations.',
            'tab:eval-tandem-transfer-main', 'lrrrrrr|r',
            [r'& \multicolumn{3}{c}{From Seaquest} & \multicolumn{3}{c|}{From Name This Game} & Native \\ \cmidrule(lr){2-4}\cmidrule(lr){5-7}',
             r'Target & SCOPE & OC tandem & Pixel tandem & SCOPE & OC tandem & Pixel tandem & training \\'],
            rows)
print('wrote reference_transfer_compact.tex and tandem_transfer_compact.tex')
