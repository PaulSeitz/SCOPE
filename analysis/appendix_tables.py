TARGET_NAMES = {
    'seaquest': 'Seaquest', 'namethisgame': 'Name This Game',
    'spaceinvaders': 'Space Invaders', 'beamrider': 'Beam Rider',
    'asteroids': 'Asteroids', 'pong': 'Pong', 'breakout': 'Breakout',
    'freeway': 'Freeway', 'phoenix': 'Phoenix',
}

TRANSFER_ARMS = (
    ('skills_ego', 'SCOPE'),
    ('skills_screen', r'$-$facing'),
    ('skills_pixel_outline', r'\shortstack[r]{Pixel\\skills}'),
    ('skills_ego_abstarget', r'\shortstack[r]{$-$relative\\encoding}'),
    ('tandem_ocnative_skills', r'\shortstack[r]{OC tandem\\skills}'),
    ('tandem_pixel_slots_skills', r'\shortstack[r]{Pixel tandem\\skills}'),
)


def read_csv(tables, name):
    with (tables / name).open(newline='') as handle:
        return list(csv.DictReader(handle))


def number(value, decimals):
    return f'{float(value):,.{decimals}f}'.replace(',', '{,}')


def summary(mean, sd, count, decimals=1):
    if int(count) == 0:
        return r'\textemdash'
    lines = [f'${number(mean, decimals)}$']
    if sd:
        lines.append(r'$\pm ' + number(sd, decimals) + '$')
    if int(count) != 5:
        lines.append(f'$(n={count})$')
    # Top-aligned so the mean shares the baseline of the row label and of
    # single-line cells; uniform struts keep all means on one line.
    return r'{\renewcommand{\arraystretch}{0.85}\begin{tabular}[t]{@{}r@{}}' + r'\\'.join(lines) + r'\end{tabular}}'


def write_table(path, title, caption, label, headers, rows):
    # tabular deliberately avoids the global scaling of tabular* bodies.
    lines = [
        '% Generated by figures/evaluation/appendix_tables.py.',
        r'\begin{table}[!htbp]', r'  \centering', r'  \footnotesize',
        r'  \setlength{\tabcolsep}{4pt}', r'  \renewcommand{\arraystretch}{1.16}',
        f'  \\caption[{title}]{{{caption}}}', f'  \\label{{{label}}}',
        r'  \begin{tabular}{@{}l' + 'r' * (len(headers) - 1) + r'@{}}',
        r'    \toprule', '    ' + ' & '.join(headers) + r' \\', r'    \midrule',
    ]
    lines.extend('    ' + ' & '.join(row) + r' \\[2pt]' for row in rows)
    lines.extend([r'    \bottomrule', r'  \end{tabular}', r'\end{table}', ''])
    path.write_text('\n'.join(lines))


def write_transfer_tables(tables):
    reference = read_csv(tables, 'reference_transfer.csv')
    transfers = {
        (row['source'], row['target'], row['arm']): row
        for row in read_csv(tables, 'all_transfer_results.csv')
    }
    rows = []
    for row in reference:
        controls = [row[key] for key in ('random_actions', 'heuristic_random', 'fixed_ego_rules')]
        rows.append([
            TARGET_NAMES[row['target']],
            *[f'${number(value, 1)}$' if value else r'\textemdash' for value in controls],
            summary(row['native_mean'], row['native_sd'], row['native_n']),
        ])
    write_table(
        tables / 'appendix_transfer_controls.tex', 'Target controls and native training',
        'Episodic returns for the transfer controls and native SCOPE agents. '
        'Each control averages 27 episodes. Native results show mean and sample SD across checkpoint means.',
        'tab:appendix-transfer-controls',
        ['Target', 'Random actions', 'Untrained skills', 'Fixed rules', 'Native SCOPE'], rows,
    )
    for source in ('seaquest', 'namethisgame'):
        arms = TRANSFER_ARMS
        caption = (f'Zero-shot transfer from {TARGET_NAMES[source]}. '
                   r'Episodic returns show mean and sample SD across five checkpoint means. '
                   r'Transferred skills use the target heuristic. '
                   r'The $-$relative encoding input (J) was evaluated on every destination shown, with five checkpoints and nine episodes per checkpoint. '
                   r'Table~\ref{tab:appendix-transfer-controls} gives the controls and native results.')
        if source == 'seaquest':
            arms += (('pqn_pixstack', r'\shortstack[r]{Pixel\\PQN}'),)
            caption += ' Pixel PQN transfers the whole agent and receives no target guidance.'
        rows = []
        for row in reference:
            target = row['target']
            if target == source:
                continue
            cells = [TARGET_NAMES[target]]
            for arm, _ in arms:
                result = transfers[source, target, arm]
                cells.append(summary(result['mean'], result['sd'], result['n']))
            rows.append(cells)
        write_table(tables / f'appendix_transfer_{source}.tex', f'Transfer from {TARGET_NAMES[source]}',
                    caption, f'tab:appendix-transfer-{source}', ['Target', *[label for _, label in arms]], rows)


def write_robustness_tables(tables):
    all_rows = read_csv(tables, 'complete_robustness.csv')
    for env in ('seaquest', 'namethisgame'):
        records = {(row['method'], row['condition']): row for row in all_rows if row['env'] == env}
        methods = list(dict.fromkeys(method for method, _ in records))
        lettered = sum(1 for m in methods if COMPLETE_LABELS.get(m, '')[1:3] == ': ' and COMPLETE_LABELS[m][0] in 'ABCDEFGHIJ')
        methods[:lettered] = sorted(methods[:lettered], key=COMPLETE_LABELS.__getitem__)
        conditions = list(dict.fromkeys(condition for _, condition in records))
        panels = [('', 'all methods', methods)]
        if env == 'seaquest':
            split = methods.index('pqn_pixel')
            panels = [('', 'SCOPE variants and tandem', methods[:split]),
                      ('_baselines', 'baselines', ['ego', *methods[split:]])]
        for suffix, description, panel in panels:
            rows = []
            for method in panel:
                label = COMPLETE_LABELS[method]
                if label[:2] in ('B:', 'C:', 'D:', 'E:', 'F:', 'G:', 'H:', 'I:', 'J:'):
                    label = label[0]
                if method in ('tandem_oc_heu', 'tandem_pixel_heu'):
                    label = label.replace('skills, heuristic', 'skills (heur.)')
                if method.startswith(('neural_', 'nesy_', 'symbolic_')):
                    label = 'NEXUS ' + label
                cells = [label]
                for condition in conditions:
                    result = records[method, condition]
                    cells.append(summary(result['mean'], result['sd'], result['n'], decimals=0))
                rows.append(cells)
            caption = (f'{TARGET_NAMES[env]} robustness ({description}). '
                       r'Episodic returns show mean and sample SD across five checkpoint means '
                       r'(nine episodes per checkpoint).')
            if suffix != '_baselines':
                caption += (r' A--J follow Figure~\ref{fig:eval-input-properties}. '
                            r'(heur.) denotes tandem skills evaluated with heuristic target selection.')
            if any(cell == r'\textemdash' for row in rows for cell in row):
                caption += ' A dash indicates an unavailable result.'
            write_table(tables / f'complete_{env}{suffix}.tex', f'{TARGET_NAMES[env]} robustness ({description})',
                        caption, f'tab:appendix-complete-{env}{suffix.replace("_", "-")}',
                        ['Method', *[COMPLETE_HEADERS[condition] for condition in conditions]], rows)


def write_appendix_tables(tables):
    write_robustness_tables(tables)
    write_transfer_tables(tables)


if __name__ == '__main__':
    write_appendix_tables(Path(__file__).resolve().parent / 'tables')
