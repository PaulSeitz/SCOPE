def plain(s):
    if not s.n:return 'TBD'
    return f'{s.mean:,.1f} ± {s.sd:,.1f}'+(f' (n={s.n})' if s.n<5 else '') if s.sd is not None else f'{s.mean:,.1f} (n={s.n})'

def tex_summary(s,bold=False):
    if not s.n:return 'TBD'
    number=f'{s.mean:,.1f}'.replace(',','{,}')
    if s.sd is not None:number+=r'\pm '+f'{s.sd:,.1f}'.replace(',','{,}')
    if bold:number=r'\mathbf{'+number+'}'
    result='$'+number+'$'
    if s.n<5:result+=f' (n={s.n})'
    return result

def tex_table(path,headers,rows,caption,label,source_break=False,size=r'\small'):
    # Source blocks avoid wasting a full column on repeated source identity.
    count=len(headers)-(1 if source_break else 0)
    visible_headers=headers[1:] if source_break else headers
    visible_headers=[r'\textbf{SCOPE}' if title=='SCOPE' else title for title in visible_headers]
    short_titles={'tab:eval-reference-transfer':'Frozen SCOPE-skill transfer and target controls','tab:eval-tandem-transfer':'Transfer of tandem-trained skills','tab:eval-skill-transfer':'Skill-interface transfer','tab:eval-native-targets':'Base performance in the additional environments','tab:appendix-pqn-transfer':'Zero-shot transfer of Seaquest-trained pixel PQN','tab:appendix-fixed-rules':'Fixed skill rules, transferred skills, and native training','tab:appendix-seaquest-counters':'Successful rescues in Seaquest','tab:appendix-pong-diagnostics':'Pong base-evaluation diagnostics'}
    text=[r'% Generated by figures/evaluation/generate.py; edit the generator, not this file.',r'\begin{table}[!htbp]',r'  \centering','  '+size,r'  \setlength{\tabcolsep}{3pt}',r'  \renewcommand{\arraystretch}{1.13}',r'  \caption['+short_titles.get(label,caption)+']{'+caption+'}',r'  \label{'+label+'}',r'  \begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}l'+'r'*(count-1)+'@{}}',r'    \toprule','    '+' & '.join(visible_headers)+r' \\',r'    \midrule']
    for i,row in enumerate(rows):
        if source_break and i%8==0:
            if i:text.append(r'    \addlinespace[3pt]')
            text.append(r'    \multicolumn{'+str(count)+r'}{@{}l}{\textit{Source: '+row[0]+r'}} \\')
            text.append(r'    \addlinespace[2pt]')
        visible=row[1:] if source_break else row
        text.append('    '+' & '.join(visible)+r' \\')
    text += [r'    \bottomrule',r'  \end{tabular*}',r'\end{table}','']
    path.write_text('\n'.join(text))

def tex_number(value, bold=False):
    result=f'{value:,.1f}'.replace(',','{,}')
    return '$'+(r'\mathbf{'+result+'}' if bold else result)+'$'

def stacked_text(text):
    return text

def stacked_summary(summary):
    if not summary.n:return stacked_text('TBD')
    parts=[tex_number(summary.mean)]
    if summary.sd is not None:
        parts.append(r'$\pm '+f'{summary.sd:,.1f}'.replace(',','{,}')+'$')
    if summary.n<5:parts.append(f'(n={summary.n})')
    return r'\begin{tabular}[c]{@{}r@{}}'+r'\\[-2pt]'.join(parts)+r'\end{tabular}'

