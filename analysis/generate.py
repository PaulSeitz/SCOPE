def best_value(values):
    """Highest value to bold; None when every compared value is equal (an all-way tie carries no ranking)."""
    if not values or (len(values)>1 and len(set(values))==1):return None
    return max(values)

def stacked_cell(summary,bold=False):
    """Mean over SD on two lines; bold applies to the mean only."""
    if summary is None:return stacked_text(r'\textemdash')
    if not summary.n:return stacked_text('TBD')
    parts=[tex_number(summary.mean,bold)]
    if summary.sd is not None:parts.append(r'$\pm '+f'{summary.sd:,.1f}'.replace(',','{,}')+'$')
    if summary.n<5:parts.append(f'(n={summary.n})')
    return r'\begin{tabular}[c]{@{}r@{}}'+r'\\[-2pt]'.join(parts)+r'\end{tabular}'

def grouped_tex_table(path,label,short_title,caption,groups,subheaders,rows,native_last=False):
    """RQ2 transfer layout: targets as rows, two-level column header, optional separated native column."""
    count=1+sum(span for _,span in groups)
    spec='l'+'r'*(count-1)
    # An empty spacer column carries the rule, which keeps it centred between the
    # last transfer column and native training under \extracolsep{\fill}.
    if native_last:
        spec=spec[:-1]+'c|r'
        subheaders=subheaders[:-1]+['',subheaders[-1]]
        rows=[row[:-1]+['',row[-1]] for row in rows]
    text=[r'% Generated by figures/evaluation/generate.py; edit the generator, not this file.',r'\begin{table}[!htbp]',r'  \centering',r'  \footnotesize',r'  \setlength{\tabcolsep}{3pt}',r'  \renewcommand{\arraystretch}{1.2}',
          # Zero rule padding so the vertical native-training rule is continuous.
          r'  \setlength{\aboverulesep}{0pt}',r'  \setlength{\belowrulesep}{0pt}',
          r'  \caption['+short_title+']{'+caption+'}',r'  \label{'+label+'}',
          r'  \begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}'+spec+'@{}}',r'    \toprule']
    cells=[''];rules=[];col=2
    for i,(title,span) in enumerate(groups):
        last=native_last and i==len(groups)-1
        if last:cells.append('')
        cells.append(r'\multicolumn{'+str(span)+'}{c}{'+title+'}' if span>1 else title)
        if title and not last:rules.append(r'\cmidrule(lr){'+f'{col}-{col+span-1}'+'}')
        col+=span
    text.append('    '+' & '.join(cells)+r' \\'+(' '+''.join(rules) if rules else ''))
    text.append('    '+' & '.join(subheaders)+r' \\')
    text.append(r'    \midrule')
    for row in rows:text.append('    '+' & '.join(row)+r' \\')
    text += [r'    \bottomrule',r'  \end{tabular*}',r'\end{table}','']
    path.write_text('\n'.join(text))

