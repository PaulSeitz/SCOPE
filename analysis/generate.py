def pong_statistics(runs,tables):
    """Retain episode-level scoring and duration evidence without inferring behavior."""
    episodes=[];checkpoints=[];summaries=[];rows=[]
    for method in ['ego','pqn_pixel']:
        observations=sorted(runs.home['pong',method,'base'],key=lambda obs:obs.seed)
        if len(observations)!=5:raise ValueError(f'Pong diagnostics require five checkpoints: {method}')
        method_episodes=[]
        for obs in observations:
            raw=json.loads(Path(obs.path).read_text())['results']['base']
            metrics=raw['episode_metrics']
            if len(metrics)!=len(obs.returns):raise ValueError(f'Pong episode count mismatch: {obs.path}')
            current=[]
            for index,(ret,metric) in enumerate(zip(obs.returns,metrics)):
                steps=float(metric['env_steps'])
                if not np.isfinite(steps) or steps<0:raise ValueError(f'Invalid Pong duration: {obs.path}')
                # Opponent points come from the episode counter. Points scored are derived as
                # return + conceded, because the player counter can miss the terminal point
                # (pixel PQN records 20 for its 21-point wins).
                conceded=float(metric['env_enemy_score'])
                if not np.isfinite(conceded) or conceded<0:raise ValueError(f'Invalid Pong opponent score: {obs.path}')
                entry={'method':method,'seed':obs.seed,'episode':index+1,'return':ret,'points_scored':ret+conceded,'points_conceded':conceded,'env_steps':steps,'near_cap':int(steps>=26900),'return_21':int(ret==21),'path':obs.path}
                episodes.append(entry);current.append(entry);method_episodes.append(entry)
            record={'method':method,'seed':obs.seed,'mean_return':obs.mean,'mean_points_scored':float(np.mean([e['points_scored'] for e in current])),'points_conceded':sum(e['points_conceded'] for e in current),'mean_env_steps':float(np.mean([e['env_steps'] for e in current])),'near_cap':sum(e['near_cap'] for e in current),'return_21':sum(e['return_21'] for e in current),'n_episodes':len(current),'path':obs.path}
            checkpoints.append(record)
            rows.append([('SCOPE' if method=='ego' else 'Pixel PQN'),str(obs.seed),f"{obs.mean:.2f}",f"{record['mean_env_steps']:,.0f}".replace(',','{,}'),f"{record['near_cap']}/9",f"{record['return_21']}/9",f"{record['mean_points_scored']:.2f}",f"{record['points_conceded']:.0f}"])
        ret=summarize(observations)
        summaries.append({'method':method,'mean_return':ret.mean,'sd_return':ret.sd,'mean_env_steps':float(np.mean([e['env_steps'] for e in method_episodes])),'near_cap':sum(e['near_cap'] for e in method_episodes),'return_21':sum(e['return_21'] for e in method_episodes),'points_conceded':sum(e['points_conceded'] for e in method_episodes),'n_episodes':len(method_episodes)})
    tex_table(tables/'pong_diagnostics_table.tex',['Method','Seed','Mean return',r'Mean steps',r'Near cap',r'Return 21',r'\shortstack[r]{Points\\scored}',r'\shortstack[r]{Points\\conceded}'],rows,
              r'Pong base-evaluation diagnostics. Each checkpoint is evaluated over nine episodes. Near cap counts episodes with at least 26,900 recorded environment steps, close to the 27,000-agent-step wrapper limit; it is a duration criterion, not a recorded termination cause. Return 21 counts episodes attaining return 21. Points scored is the mean per episode, derived as return plus points conceded; points conceded is the total over the nine episodes, taken from the recorded opponent score.',
              'tab:appendix-pong-diagnostics')
    ref,pixel=summaries
    capped=[e for e in episodes if e['method']=='ego' and e['near_cap']]
    most_capped=max(e['points_scored'] for e in capped) if capped else 0
    if ref['points_conceded']!=0 or not capped or most_capped>3:
        raise ValueError('Pong paragraph claims (no conceded points, at most three points in capped episodes) no longer hold; revise the text.')
    text=[r'% Generated by figures/evaluation/generate.py; original return lists and episode_metrics.',
          f"Across 45 episodes, SCOPE has mean return ${ref['mean_return']:.2f} \\pm {ref['sd_return']:.2f}$ (sample SD across five checkpoint means). Of these episodes, {ref['near_cap']} approach the step cap and {ref['return_21']} attain return 21. Pixel PQN reaches return 21 in all {pixel['n_episodes']} episodes, with {pixel['near_cap']} near the cap. Mean recorded duration is {ref['mean_env_steps']:,.0f} steps for SCOPE and {pixel['mean_env_steps']:,.0f} for pixel PQN.",
          f"SCOPE concedes no point in any of the {ref['n_episodes']} episodes. Episodes that reach the step cap end with only zero to {most_capped:.0f} points scored by the agent, which returns the ball reliably but rarely converts rallies into points, while finished episodes end with return 21. Episode-level values and original source paths are retained in \\path{{figures/evaluation/tables/pong_episodes.csv}}.",
          r'\input{figures/evaluation/tables/pong_diagnostics_table.tex}']
    (tables/'pong_diagnostics.tex').write_text('\n\n'.join(text)+'\n')
    for name,records in [('pong_episodes',episodes),('pong_checkpoints',checkpoints),('pong_summary',summaries)]:
        write_csv(tables/(name+'.csv'),records,list(records[0]))


