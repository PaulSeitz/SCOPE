def rescue_statistics(runs,tables):
    """Export the recorded per-episode counter separately from return statistics."""
    checkpoints=[];summaries=[];values={}
    for method in ['ego','pqn_pixel']:
        for condition in ['base','no_enemies']:
            observations=[]
            for obs in runs.home['seaquest',method,condition]:
                raw=json.loads(Path(obs.path).read_text())['results'][condition]
                counts=tuple(float(ep['env_rescues']) for ep in raw['episode_metrics'])
                if len(counts)!=9 or any(not np.isfinite(v) or v<0 for v in counts):
                    raise ValueError(f'Invalid rescue counters: {obs.path}: {condition}')
                mean=float(np.mean(counts))
                if not np.isclose(mean,raw['mean_env_rescues'],rtol=1e-10,atol=1e-8):
                    raise ValueError(f'Rescue mean mismatch: {obs.path}: {condition}')
                observations.append(Observation(obs.seed,mean,counts,obs.path))
                checkpoints.append({'method':method,'condition':condition,'seed':obs.seed,'mean_rescues':mean,'n_episodes':len(counts),'path':obs.path})
            summary=summarize(observations)
            if summary.n!=5:raise ValueError(f'Rescue paragraph requires five checkpoints: {method}/{condition}')
            values[method,condition]=summary
            summaries.append({'method':method,'condition':condition,'mean':summary.mean,'sd':summary.sd,'n':summary.n})
    def number(method,condition):
        value=values[method,condition]
        return f'${value.mean:.2f} \\pm {value.sd:.2f}$'
    text=[r'% Generated by figures/evaluation/generate.py; metrics from original episode_metrics.',
          r'Successful rescues are measured from increases in the environment\textquotesingle s \path{successful_rescues} counter. SCOPE averages '+number('ego','base')+' rescues per episode in base Seaquest and '+number('ego','no_enemies')+' after enemy removal. Pixel PQN averages '+number('pqn_pixel','base')+' and '+number('pqn_pixel','no_enemies')+', respectively.',
          r'Values show the mean and sample standard deviation across five checkpoint-level means, each based on nine evaluation episodes. These counters establish the difference in completed rescues per episode; they do not measure rescue rate per environment step. The corresponding checkpoint values and original source paths are exported in \path{figures/evaluation/tables/rescue_checkpoint_means.csv}.','']
    (tables/'seaquest_rescues.tex').write_text('\n\n'.join(text))
    write_csv(tables/'rescue_checkpoint_means.csv',checkpoints,list(checkpoints[0]))
    write_csv(tables/'rescue_summary.csv',summaries,list(summaries[0]))


def seaquest_counter_table(runs,renderer,tables):
    metrics=['env_rescues','env_steps']
    methods=['ego','screen','oc','pixel','nocross','tandem_oc','tandem_pixel','pqn_pixel','pqn_oc','pqn_oc_large','symbolic_pixel','hrl_pixel','hrl_oc']
    rerun={'symbolic_pixel','hrl_pixel','hrl_oc'}  # counters from the separate rescue rerun, marked with a dagger
    # Same row names as the complete robustness tables (appendix_tables.COMPLETE_LABELS).
    names={'ego': 'A: SCOPE', 'screen': 'B', 'oc': 'H', 'pixel': 'I', 'nocross': 'Acting skill only', 'tandem_oc': 'OC tandem', 'tandem_pixel': 'Pixel tandem', 'pqn_pixel': 'Pixel PQN', 'pqn_oc': 'OC PQN', 'pqn_oc_large': 'OC PQN, 3$\\times$128', 'symbolic_pixel': 'NEXUS Symbolic, pixels', 'hrl_pixel': 'Pixel HRL', 'hrl_oc': 'OC HRL'}
    checkpoints=[];summaries=[];latex=[];preview=[]
    for method in methods:
        for condition in ['base','no_enemies']:
            ss=[]
            for metric in metrics:
                observations=[]
                for obs in (runs.rescue_rerun[method,condition] if method in rerun else runs.home['seaquest',method,condition]):
                    raw=json.loads(Path(obs.path).read_text())['results'][condition]
                    episodes=raw.get('episode_metrics',[])
                    if not episodes or any(metric not in ep for ep in episodes):continue
                    counts=tuple(float(ep[metric]) for ep in episodes)
                    if len(counts)!=9 or any(not np.isfinite(v) or v<0 for v in counts):raise ValueError(f'Invalid Seaquest counter: {obs.path}/{metric}')
                    mean=float(np.mean(counts))
                    if not np.isclose(mean,raw['mean_'+metric],rtol=1e-10,atol=1e-8):raise ValueError(f'Seaquest counter mean mismatch: {obs.path}/{metric}')
                    observations.append(Observation(obs.seed,mean,counts,obs.path))
                    checkpoints.append({'method':method,'condition':condition,'metric':metric,'seed':obs.seed,'mean':mean,'n_episodes':len(counts),'path':obs.path})
                s=summarize(observations);ss.append(s)
                if s.n:summaries.append({'method':method,'condition':condition,'metric':metric,'mean':s.mean,'sd':s.sd,'n':s.n})
            if any(s.n for s in ss):
                if any(s.n!=5 for s in ss):raise ValueError(f'Rescue table requires five checkpoints: {method}/{condition}')
                label='Base' if condition=='base' else 'No enemies'
                mark='$^\\dagger$' if method in rerun else ''
                latex.append([names[method]+mark,label,*[tex_summary(s) for s in ss]])
                preview.append([LABELS[method]+('†' if method in rerun else ''),label,*[plain(s) for s in ss]])
    headers=['Method','Condition','Rescues','Episode steps']
    tex_table(tables/'seaquest_counters.tex',headers,latex,
              r'Successful rescues per episode in Seaquest for all learned configurations with recorded rescue counters, in base and no-enemies evaluations. Entries are mean $\pm$ sample SD across five checkpoint means, each based on nine episodes. A--J follow Figure~\ref{fig:eval-input-properties}. Rescues count positive increments of successful rescues; episode steps are recorded environment steps per episode, with a limit of 27,000 agent steps. $^\dagger$Counters from a separate evaluation pass with the same checkpoints, seeds, and protocol; for pixel inputs its episodes differ from the reported return evaluation.',
              'tab:appendix-seaquest-counters',size=r'\footnotesize')
    renderer.table_image('table06_seaquest_counters',headers,preview,font_size=7)
    write_csv(tables/'seaquest_counter_checkpoints.csv',checkpoints,list(checkpoints[0]))
    write_csv(tables/'seaquest_counter_summary.csv',summaries,list(summaries[0]))


def fixed_rule_table(runs,renderer,tables):
    """Appendix: hand-crafted fixed skill rules against transferred and natively trained skills."""
    headers=['Target',r'\shortstack[r]{Fixed\\rules}',r'\shortstack[r]{Transfer from\\Seaquest}',r'\shortstack[r]{Transfer from\\Name This Game}',r'\shortstack[r]{Native\\training}']
    preview_headers=['Target','Fixed\nrules','Transfer from\nSeaquest','Transfer from\nName This Game','Native\ntraining']
    latex=[];preview=[];records=[];bold=[]
    for i,target in enumerate(TARGET_ORDER):
        fixed=runs.control(target,'fixed_ego_rules')
        transfers=[runs.transferred('skills_ego',source,target) if source!=target else None for source in HOMES]
        native=runs.base(target,'ego')
        # Bold the strongest of the fixed rules and the transferred skills; native training is context.
        candidates=[fixed['mean'] if fixed else None]+[s.mean if s is not None and s.n else None for s in transfers]
        best=max((c for c in candidates if c is not None),default=None)
        row_tex=[NAMES[target],stacked_text(tex_number(fixed['mean'],fixed['mean']==best) if fixed else 'TBD')]
        row_plain=[NAMES[target],f'{fixed["mean"]:,.1f}' if fixed else 'TBD']
        if fixed and fixed['mean']==best:bold.append((i,1))
        for j,s in enumerate(transfers):
            if s is None:
                row_tex.append(stacked_text(r'\textemdash'));row_plain.append('—');continue
